/**
 * Serializers for CSS custom properties and W3C design tokens.
 */

import { codeToOklch, fromHex, luminance } from './color.js';
import { mirrorStep } from './core.js';

/* ------------------------------------------------------------- formats */

function toRgb(code) {
	return `rgb(${code[0]} ${code[1]} ${code[2]})`;
}

function toHsl(code) {
	const [r, g, b] = code.map((v) => v / 255);
	const max = Math.max(r, g, b);
	const min = Math.min(r, g, b);
	const l = (max + min) / 2;
	const dd = max - min;
	let h = 0;
	let s = 0;
	if (dd > 1e-9) {
		s = dd / (1 - Math.abs(2 * l - 1));
		if (max === r) h = ((g - b) / dd) % 6;
		else if (max === g) h = (b - r) / dd + 2;
		else h = (r - g) / dd + 4;
		h *= 60;
		if (h < 0) h += 360;
	}
	const round = (v) => Math.round(v * 10) / 10;
	return `hsl(${round(h)} ${round(s * 100)}% ${round(l * 100)}%)`;
}

function toOklch(code, precision = 4) {
	const [l, c, h] = codeToOklch(code);
	const lp = (l * 100).toFixed(2);
	const cp = c.toFixed(precision);
	// An achromatic color has no meaningful hue; `none` says so honestly.
	const hp = c < 1e-4 ? 'none' : h.toFixed(2);
	return `oklch(${lp}% ${cp} ${hp})`;
}

/**
 * The guarantee is proved on the 8-bit codes. hex and rgb are exact
 * round-trips of those integers, so the proof travels with the output. hsl and
 * oklch are re-resolved by the browser through its own float pipeline -- and on
 * a wide-gamut display an oklch() value resolves in the display's space, not
 * sRGB -- so for those the proof covers the source only.
 */
export const GUARANTEE = {
	hex: 'proven-on-output',
	rgb: 'proven-on-output',
	hsl: 'proven-on-source-only',
	oklch: 'proven-on-source-only',
};

export const FORMAT_LABEL = {
	hex: 'hex',
	rgb: 'rgb()',
	hsl: 'hsl()',
	oklch: 'oklch()',
};

export function formatColor(hex, format, precision = 4) {
	const code = fromHex(hex);
	if (!code) return hex;
	switch (format) {
		case 'rgb':
			return toRgb(code);
		case 'hsl':
			return toHsl(code);
		case 'oklch':
			return toOklch(code, precision);
		default:
			return hex;
	}
}

/* ----------------------------------------------------------------- CSS */

export function exportCss(scales, anchors, opts = {}) {
	const {
		format = 'hex',
		mirror = true,
		layer = true,
		comments = true,
		precision = 4,
	} = opts;

	const n = scales[0]?.swatches.length ?? 0;
	const fmt = (hex) => formatColor(hex, format, precision);
	const lines = [];
	const ind = layer ? '\t\t' : '\t';

	lines.push(`${ind}color-scheme: light dark;`);
	// The anchors mirror just like the scale tokens do, so --background is the
	// page background in both schemes and --text is always legible on it.
	if (mirror) {
		lines.push(`${ind}--background: light-dark(${fmt(anchors.bg.hex)}, ${fmt(anchors.fg.hex)});`);
		lines.push(`${ind}--text: light-dark(${fmt(anchors.fg.hex)}, ${fmt(anchors.bg.hex)});`);
	} else {
		lines.push(`${ind}--background: ${fmt(anchors.bg.hex)};`);
		lines.push(`${ind}--text: ${fmt(anchors.fg.hex)};`);
	}

	for (const s of scales) {
		lines.push('');
		for (let token = 1; token <= n; token++) {
			const light = s.swatches[token - 1].hex;
			const dark = s.swatches[mirrorStep(token, n) - 1].hex;
			const value = mirror
				? `light-dark(${fmt(light)}, ${fmt(dark)})`
				: fmt(light);
			let line = `${ind}--${s.name}-${token}: ${value};`;
			if (comments && format !== 'hex') {
				line += mirror ? ` /* ${light} ${dark} */` : ` /* ${light} */`;
			}
			lines.push(line);
		}
	}

	const body = [`${layer ? '\t' : ''}:root {`, ...lines, `${layer ? '\t' : ''}}`].join(
		'\n',
	);

	const preface = buildPreface(opts, format);
	const out = layer ? `@layer colors {\n${body}\n}` : body;
	return `${preface}\n${out}\n`;
}

function buildPreface(opts, format) {
	const d = opts.d ?? 3;
	const threshold = opts.threshold ?? 4.5;
	const n = opts.n ?? 6;
	const status = GUARANTEE[format];
	const lines = [
		'/*',
		' * Color tokens — generated by https://bitstorm.org/color-tokens',
		' *',
		` * Any two tokens whose index differs by ${d} or more reach ${threshold}:1,`,
		' * for every color family, in light mode and in dark mode alike.',
		` * Index 1 sits closest to the page background, index ${n} contrasts most.`,
		' *',
	];
	if (status === 'proven-on-output') {
		lines.push(
			` * Verified on these exact ${FORMAT_LABEL[format]} values.`,
		);
	} else {
		lines.push(
			` * NOTE: verified on the 8-bit hex values, not on these ${FORMAT_LABEL[format]}`,
			' * ones. The browser re-resolves them through its own pipeline, and on a',
			' * wide-gamut display they resolve outside sRGB. Export as hex if you need',
			' * the guarantee to hold on the shipped values.',
		);
	}
	lines.push(
		' *',
		' * Holds for opaque colors only: no alpha, opacity, color-mix() or blend',
		' * modes, and no hand-edited values.',
		' */',
	);
	return lines.join('\n');
}

/* ---------------------------------------------------------------- JSON */

/** W3C Design Tokens draft format: https://www.designtokens.org/tr/drafts/format/ */
export function exportTokens(scales, anchors, opts = {}) {
	const { format = 'hex', precision = 4, mirror = true } = opts;
	const n = scales[0]?.swatches.length ?? 0;
	const fmt = (hex) => formatColor(hex, format, precision);

	const anchorPair = (lightHex, darkHex) =>
		mirror
			? {
					$value: fmt(lightHex),
					$extensions: {
						'org.bitstorm.color-tokens': {
							light: fmt(lightHex),
							dark: fmt(darkHex),
							css: `light-dark(${fmt(lightHex)}, ${fmt(darkHex)})`,
						},
					},
				}
			: { $value: fmt(lightHex) };

	const out = {
		$schema: 'https://www.designtokens.org/schema.json',
		color: {
			$type: 'color',
			background: anchorPair(anchors.bg.hex, anchors.fg.hex),
			text: anchorPair(anchors.fg.hex, anchors.bg.hex),
		},
	};

	for (const s of scales) {
		const group = { $type: 'color' };
		for (let token = 1; token <= n; token++) {
			const light = s.swatches[token - 1].hex;
			const dark = s.swatches[mirrorStep(token, n) - 1].hex;
			group[String(token)] = mirror
				? {
						$value: fmt(light),
						$extensions: {
							'org.bitstorm.color-tokens': {
								light: fmt(light),
								dark: fmt(dark),
								css: `light-dark(${fmt(light)}, ${fmt(dark)})`,
							},
						},
					}
				: { $value: fmt(light) };
		}
		out.color[s.name] = group;
	}
	return out;
}
